import type { SealId } from './seals'

/**
 * 十二手印示意图数据（viewBox 120×100）。
 * 采用摄像头视角：手背朝向镜头，拇指多收在靠近自己的一侧被遮挡，因此图中不画拇指；
 * 画面做了镜像，画面左侧即玩家左手，与摄像头预览一致。
 * 部件按数组顺序从后往前绘制，后绘制的遮挡先绘制的。
 */
type Pt = [number, number]
type Hand = 'L' | 'R'

export type GuidePart =
  | { k: 'arm'; h: Hand; from: Pt; to: Pt }
  | { k: 'palm'; h: Hand; cx: number; cy: number; rx: number; ry: number }
  /** 拳头 / 平掌块，lines 为指缝方向 */
  | { k: 'block'; h: Hand; x: number; y: number; w: number; hgt: number; lines?: 'h' | 'v'; n?: number }
  | { k: 'finger'; h: Hand; pts: Pt[]; w?: number }
  | { k: 'dot'; h: Hand; x: number; y: number; r?: number }

export interface SealGuide {
  parts: GuidePart[]
  /** 结印步骤 */
  steps: string[]
  /** 摄像头视角下的识别要点 */
  tip: string
}

const armL = (to: Pt, from: Pt = [6, 100]): GuidePart => ({ k: 'arm', h: 'L', from, to })
const armR = (to: Pt, from: Pt = [114, 100]): GuidePart => ({ k: 'arm', h: 'R', from, to })
const f = (h: Hand, w: number, ...pts: Pt[]): GuidePart => ({ k: 'finger', h, pts, w })

